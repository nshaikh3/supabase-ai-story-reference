export function publicEnvironmentFromStatus(status) {
  if (status.API_URL !== "http://127.0.0.1:55321") throw new Error("Refusing environment setup for a different Supabase URL.");
  if (typeof status.PUBLISHABLE_KEY !== "string" || !/^sb_publishable_[A-Za-z0-9_-]+$/.test(status.PUBLISHABLE_KEY)) {
    throw new Error("Local status did not contain a valid publishable key.");
  }
  // Deliberate allowlist: never serialize the full CLI status, which includes secrets.
  return "# Generated by npm run local:env; local public configuration only.\n" +
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}\n` +
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}\n` +
    "NEXT_PUBLIC_APP_URL=http://127.0.0.1:3100\n";
}
